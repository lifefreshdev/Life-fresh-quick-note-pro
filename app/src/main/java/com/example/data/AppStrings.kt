    fun getResourceId(key: String): Int? {
        return STRING_RESOURCE_MAP[key]
    }

    @Composable
    @ReadOnlyComposable
    fun get(key: String): String {
        val meta = LocalActiveLanguageMetadata.current
        val resId = STRING_RESOURCE_MAP[key]
        if (resId != null) {
            val context = LocalContext.current
            val currentConfig = LocalConfiguration.current
            val targetLocale = AppLanguageManager.getJavaLocale(meta.localeTag)

            val matchesLocale = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N) {
                currentConfig.locales.size() > 0 && currentConfig.locales[0].language.equals(targetLocale.language, ignoreCase = true)
            } else {
                @Suppress("DEPRECATION")
                currentConfig.locale != null && currentConfig.locale.language.equals(targetLocale.language, ignoreCase = true)
            }

            if (matchesLocale) {
                return stringResource(resId)
            }

            // If composition config does not match target language yet, resolve via localized configuration context
            val localizedValue = resolveFromContext(context, resId, targetLocale)
            if (localizedValue != null) {
                return localizedValue
            }
        }

        // XML resource not found or resolution failed -> fall back to map
        return getString(key, meta.code)
    }

    fun getString(key: String, language: AppLanguage): String {
        return getString(key, language.code)
    }

    fun getString(context: Context, key: String, languageCode: String? = null): String {
        val code = (languageCode ?: AppLanguageManager.getLanguageCode(context)).lowercase()
        val resId = STRING_RESOURCE_MAP[key]
        if (resId != null) {
            val meta = LanguagePackManager.getMetadata(code) ?: AppLanguage.fromCode(code).toMetadata()
            val targetLocale = AppLanguageManager.getJavaLocale(meta.localeTag)
            val localizedValue = resolveFromContext(context, resId, targetLocale)
            if (localizedValue != null) {
                return localizedValue
            }
        }
        return getString(key, code)
    }

    fun getString(key: String, languageCode: String): String {
        val code = languageCode.lowercase()
        // 1. Check if a dynamic downloaded language pack has this translation
        val customString = LanguagePackManager.getString(code, key)
        if (!customString.isNullOrBlank()) {
            return customString
        }

        // 2. Fall back to bundled language tables
        val map = when (code) {
            "en" -> ENGLISH_STRINGS
            "hi" -> HINDI_STRINGS
            "ur" -> URDU_STRINGS
            "ta" -> TAMIL_STRINGS
            else -> ENGLISH_STRINGS
        }
        return map[key] ?: ENGLISH_STRINGS[key] ?: key
    }

    private fun resolveFromContext(context: Context, resId: Int, targetLocale: Locale): String? {
        return try {
            val config = Configuration(context.resources.configuration)
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N) {
                config.setLocales(LocaleList(targetLocale))
            } else {
                @Suppress("DEPRECATION")
                config.locale = targetLocale
            }
            val localizedContext = context.createConfigurationContext(config)
            localizedContext.resources.getString(resId)
        } catch (_: Throwable) {
            null
        }
    }

